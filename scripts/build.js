// Builds the deployable site into dist/.
//
// The version is "<package.json version>+<hash of the built files>", so any
// change to the app produces a new version (and a new service-worker cache)
// while an unchanged tree always builds to the same one. Bump package.json
// for releases; the hash takes care of every deploy in between.
//
//   node scripts/build.js

import { createHash } from 'node:crypto';
import { cp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = path.join(root, 'dist');
const STATIC = ['index.html', 'styles.css', 'manifest.webmanifest', 'src', 'icons'];

await rm(dist, { recursive: true, force: true });
for (const entry of STATIC) {
  await cp(path.join(root, entry), path.join(dist, entry), {
    recursive: true,
    filter: (src) => path.basename(src) !== '.DS_Store',
  });
}

const files = (await listFiles(dist)).sort();
const hash = createHash('sha256');
for (const file of files) {
  hash.update(file);
  hash.update(await readFile(path.join(dist, file)));
}

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const version = `${pkg.version}+${hash.digest('hex').slice(0, 8)}`;

await writeFile(
  path.join(dist, 'src/version.js'),
  `// Generated by scripts/build.js\nexport const VERSION = ${JSON.stringify(version)};\n`,
);

const sw = await readFile(path.join(root, 'sw.js'), 'utf8');
await writeFile(
  path.join(dist, 'sw.js'),
  fill(sw, {
    "'__VERSION__'": JSON.stringify(version),
    '[/* __ASSETS__ */]': JSON.stringify(['./', ...files], null, 2),
  }),
);

console.log(`Built ${version}: ${files.length + 1} files in ${path.relative(process.cwd(), dist) || '.'}`);

async function listFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await listFiles(full)));
    else out.push(path.relative(dist, full).split(path.sep).join('/'));
  }
  return out;
}

function fill(template, replacements) {
  let out = template;
  for (const [placeholder, value] of Object.entries(replacements)) {
    if (!out.includes(placeholder)) throw new Error(`Placeholder ${placeholder} not found in sw.js`);
    out = out.replace(placeholder, () => value);
  }
  return out;
}
